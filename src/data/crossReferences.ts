/** Offline cross-reference map (curated subset for study). Keys: bookId:chapter:verse */

export interface CrossRefTarget {
  bookId: string;
  chapter: number;
  verse: number;
}

type CrossRefMap = Record<string, CrossRefTarget[]>;

function ref(bookId: string, chapter: number, verse: number): CrossRefTarget {
  return { bookId, chapter, verse };
}

function key(bookId: string, chapter: number, verse: number): string {
  return `${bookId}:${chapter}:${verse}`;
}

